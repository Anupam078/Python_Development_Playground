# Creating strings

str1 = "Hello"
str2 = "World"

# Concatenation
print("Concatenation:", str1 + " " + str2)

# Duplication
print("Duplication:", str1 * 3)

# String Indexing
print("First character:", str1[0])
print("Last character:", str1[-1])

# String Slicing
print("Slice (0:4):", str1[0:4])
print("Slice (1:5):", str1[1:5])

# String Membership
print("'H' in str1:", 'H' in str1)
print("'z' in str1:", 'z' in str1)